import pathlib
from pyrtma.parser import Parser
from ruamel.yaml import YAML
from typing import Any
from pyrtma.__version__ import __version__


class NullRepresenter:
    def __init__(self):
        self.count = 0

    def __call__(self, repr, data):
        return repr.represent_scalar("tag:yaml.org,2002:null", "null")


class YAMLCompiler:
    def __init__(self, parser: Parser, filename: str, debug: bool = False):
        self.filename = filename
        self.debug = debug
        self.parser = parser

    def generate(self, out_filepath: pathlib.Path):
        """Write every parsed definition into one YAML file, with an index for it.

        The YAML file is a message definitions file. It holds the core
        definitions too, so the index beside it, ``<name>.defs``, turns off
        ``import_coredefs``; compile it with ``-i <name>.defs``.

        Args:
            out_filepath: The YAML file to write, such as ``defs_combined.yaml``.
        """
        yaml = YAML()
        yaml.default_flow_style = False
        my_represent_none = NullRepresenter()
        yaml.representer.add_representer(type(None), my_represent_none)

        meta_dict: dict[str, Any] = {
            "COMPILED_PYRTMA_VERSION": __version__,
            "AUTOGENERATED": True,
        }

        d: dict[str, dict[str, Any] | None] = {
            "metadata": {},
        }

        for k, v in self.parser.yaml_dict.items():
            if isinstance(v, dict) and len(v) == 0:
                d[k] = None
            else:
                d[k] = v
        for k, v in meta_dict.items():
            if d["metadata"] is None:
                d["metadata"] = {}
            if isinstance(d["metadata"], dict) and isinstance(v, dict) and len(v) == 0:
                d["metadata"][k] = None
            elif isinstance(d["metadata"], dict):
                d["metadata"][k] = v

        yaml.dump(d, out_filepath)

        # A message definitions file can't hold compiler options, so they go
        # in an index file of their own.
        index = out_filepath.with_suffix(".defs")
        index.write_text(
            f"# {index.name}\n"
            "# DO NOT EDIT BY HAND. FILE IS AUTO-GENERATED.\n"
            f"# This index was auto-generated by pyrtma.compile version {__version__}\n"
            f"# for {out_filepath.name}, which already holds the core definitions.\n"
            "\n"
            "compiler_options:\n"
            "  import_coredefs: false\n"
            "\n"
            "index:\n"
            f"  {out_filepath.stem}: {out_filepath.name}\n",
            encoding="utf-8",
        )
